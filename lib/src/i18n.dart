String Function(String, [List<String>?]) makeTranslator(String lang) {
  final table = strings[lang] ?? strings['ru']!;

  String tr(String key, [List<String>? fmt]) {
    final value = table[key] ?? key;
    if (fmt == null || fmt.isEmpty) return value;
    var out = value;
    for (var i = 0; i < fmt.length; i++) {
      out = out.replaceFirst('{}', fmt[i]);
    }
    return out;
  }

  return tr;
}